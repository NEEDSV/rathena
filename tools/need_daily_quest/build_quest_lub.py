"""Rebuild OngoingQuestInfoList_True.lub with the NEED daily quest entries.

usage: build_quest_lub.py <original.lub> <luac.exe> <out.lub> <workdir> <quests.json> <encoding>
  quests.json  from gen_quests.py (quests_kr.json -> cp949, quests_en.json -> ascii-safe cp949)

1. load the original (32 bit Lua 5.1 bytecode) with lupa after widening size_t
2. serialise every global the chunk created back to Lua source (strings byte exact)
3. add the NEED entries, compile with the 32 bit luac 5.1.4
4. reload the result and compare every original entry value by value; refuse on any difference

Derived from dqtest/dqbtn_poc/tools/gen_quest_lub.py (daily mission UI PoC, 2026-10-21).
"""
import json, os, sys, subprocess
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lub32to64 import convert
import lupa.lua51 as L

src_lub, luac, out_lub, work, quests_json, ENC = sys.argv[1:7]
NEED_QUESTS = {int(k): v for k, v in json.load(open(quests_json, encoding='utf-8')).items()}
assert NEED_QUESTS and all(99000 <= i <= 99999 for i in NEED_QUESTS), sorted(NEED_QUESTS)

# ---------------------------------------------------------------- load original
def run_chunk(data):
    lua = L.LuaRuntime(encoding=None)
    before = set(lua.globals().keys())
    lua.eval('function(s) local f, e = loadstring(s); if not f then error(e) end; f() end')(convert(data))
    g = lua.globals()
    return lua, {k: g[k] for k in g.keys() if k not in before}

lua0, new_globals = run_chunk(open(src_lub, 'rb').read())
print('globals created by chunk:', [k.decode() for k in new_globals])
lua_type = lua0.eval('type')

def to_py(v):
    t = lua_type(v)
    if t == b'table':
        return {k if not isinstance(k, float) or not k.is_integer() else int(k): to_py(x) for k, x in v.items()}
    if isinstance(v, float) and v.is_integer():
        return int(v)
    if t in (b'string', b'number', b'boolean'):
        return v
    raise TypeError('unsupported lua type %r' % t)

orig = {k: to_py(v) for k, v in new_globals.items()}

# ---------------------------------------------------------------- serialise
def lstr(b):
    out = bytearray(b'"')
    for c in b:
        if c == 0x22: out += b'\\"'
        elif c == 0x5C: out += b'\\\\'
        elif c == 0x0A: out += b'\\n'
        elif c == 0x0D: out += b'\\r'
        elif c < 0x20 or c == 0x7F: out += b'\\%d' % c   # decimal escape; next char never a digit-ambiguity:
        else: out.append(c)
    out += b'"'
    return bytes(out)

def needs_safe_escape(b):
    return b

def lval(v, ind=1):
    if isinstance(v, bool): return b'true' if v else b'false'
    if isinstance(v, int): return str(v).encode()
    if isinstance(v, float): return repr(v).encode()
    if isinstance(v, bytes): return lstr(v)
    if isinstance(v, str): return lstr(v.encode(ENC))
    if isinstance(v, list): v = {i + 1: x for i, x in enumerate(v)}
    if isinstance(v, dict):
        pad = b'\t' * ind
        parts = []
        for k in sorted(v, key=lambda k: (0, k) if isinstance(k, int) else (1, k if isinstance(k, bytes) else k.encode(ENC))):
            if isinstance(k, int): kk = b'[%d]' % k
            else:
                kb = k if isinstance(k, bytes) else k.encode(ENC)
                kk = kb if kb.replace(b'_', b'a').isalnum() and not kb[:1].isdigit() else b'[' + lstr(kb) + b']'
            parts.append(pad + kk + b' = ' + lval(v[k], ind + 1))
        return b'{\n' + b',\n'.join(parts) + b'\n' + b'\t' * (ind - 1) + b'}'
    raise TypeError(type(v))

# decimal escapes followed by a digit would be misread: use 3 digit escapes to be safe
def lstr(b):  # noqa: F811
    out = bytearray(b'"')
    for c in b:
        if c == 0x22: out += b'\\"'
        elif c == 0x5C: out += b'\\\\'
        elif c < 0x20 or c == 0x7F: out += b'\\%03d' % c
        else: out.append(c)
    out += b'"'
    return bytes(out)

qkey = b'QuestInfoList'
assert qkey in orig and len(orig) == 1, 'unexpected globals: %r' % list(orig)
merged = dict(orig[qkey])
clash = [i for i in NEED_QUESTS if i in merged]
assert not clash, 'NEED quest ids already used: %r' % clash
for i, q in NEED_QUESTS.items():
    merged[i] = q

os.makedirs(work, exist_ok=True)
lua_src = os.path.join(work, 'OngoingQuestInfoList_True.lua')
with open(lua_src, 'wb') as f:
    f.write(b'-- generated by build_quest_lub.py from the client lub + NEED daily quest entries\n')
    f.write(b'QuestInfoList = ' + lval(merged) + b'\n')
print('lua source', os.path.getsize(lua_src), 'bytes,', len(merged), 'quests')

r = subprocess.run([luac, '-s', '-o', out_lub, lua_src], capture_output=True)
if r.returncode:
    sys.exit('luac failed: ' + r.stderr.decode(ENC, 'replace'))
print('compiled', out_lub, os.path.getsize(out_lub), 'bytes')

# ---------------------------------------------------------------- verify
data = open(out_lub, 'rb').read()
assert data[:5] == b'\x1bLuaQ' and data[8] == 4, 'output is not 32 bit Lua 5.1 bytecode'
lua1, g1 = run_chunk(data)
lua_type = lua1.eval('type')
chk = {k: to_py(v) for k, v in g1.items()}
assert list(chk) == [qkey], list(chk)
new = chk[qkey]
bad = [i for i in orig[qkey] if new.get(i) != orig[qkey][i]]
assert not bad, 'original entries differ: %r' % bad[:10]
extra = sorted(set(new) - set(orig[qkey]))
assert extra == sorted(NEED_QUESTS), extra
for i in NEED_QUESTS:
    assert new[i][b'Title'] == NEED_QUESTS[i]['Title'].encode(ENC)
    assert new[i][b'IconName'] == b'ico_dq.bmp'
print('verify OK: %d original entries identical, added %r' % (len(orig[qkey]), extra))
