# -*- coding: utf-8 -*-
"""NEED rune tablet buff tooltip generator (display only).

    python tools/need_rune_tooltip/generate.py --kr <KR client repo> --en <EN client repo> --out <dir>
    python tools/need_rune_tooltip/generate.py --kr <KR> --en <EN> --install      # write into the repos
    python tools/need_rune_tooltip/generate.py --kr <KR> --en <EN> --check        # exit 1 on any drift

The client cannot put server values into a status tooltip (only the timer line is formatted, see
md/rune_tablet_tooltip_20261019). So every reachable rune display state gets its own EFST whose
tooltip already holds the exact summed values. A state = (active 2/4/6-piece tiers, summed value
of every bonus) for one set; (grade 0..15, pieces 0..6) maps onto it.

Single source of truth: db/rune_db.yml. The set scripts are evaluated here for every (grade,
pieces); a script line this evaluator does not understand stops the generator. The server
compares a hash of the loaded scripts with the one written here and hides the icon on mismatch,
and @runetooltipcheck compares every state against what pc_bonus actually received.

Outputs (paths relative to the repos):
  rathena  src/map/rune_display_table.inc                       server table (state grid + expected bonuses)
  KR + EN  data/luafiles514/lua files/stateicon/efstids.lub       EFST symbols   (identical KR/EN)
           data/luafiles514/lua files/stateicon/stateiconimginfo.lub  icon file   (identical KR/EN)
           data/luafiles514/lua files/stateicon/stateiconinfo_f.lub   HaveEfstImg (identical KR/EN)
           data/texture/effect/need_rune_<set>.tga                    icons       (identical KR/EN)
  KR       data/luafiles514/lua files/stateicon/stateiconinfo.lub     KR tooltip text
  EN       data/luafiles514/lua files/stateicon/stateiconinfo.lub     EN tooltip text
Every lub change is one marked block; regenerating replaces only that block.
"""
import argparse
import hashlib
import os
import re
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
RUNE_DB = os.path.join(REPO, 'db', 'rune_db.yml')
SERVER_INC = os.path.join('src', 'map', 'rune_display_table.inc')

STATEICON = os.path.join('data', 'luafiles514', 'lua files', 'stateicon')
EFFECT = os.path.join('data', 'texture', 'effect')
ICON_SRC = os.path.join('data', 'texture', '유저인터페이스', 'runesystem', 'rune_icon')

BEGIN = '-- [NEED RUNE TOOLTIP BEGIN] generated by rathena tools/need_rune_tooltip/generate.py - do not edit'
END = '-- [NEED RUNE TOOLTIP END]'
EFST_ANCHOR = b'\tEFST_NEED_GOLDPC = 1690,\r\n'
NO_TYPE2 = 'RUNE_DISPLAY_NO_TYPE2'
TGA_FOOTER = b'\x00' * 8 + b'TRUEVISION-XFILE.\x00'


def fail(msg):
    raise SystemExit('GENERATE FAILED: ' + msg)


# ---------------------------------------------------------------- script hash (mirrors rune.cpp)
def fnv1a64(data):
    h = 0xcbf29ce484222325
    for b in data:
        h ^= b
        h = (h * 0x100000001b3) & 0xffffffffffffffff
    return h


def normalize_script(s):
    return '\n'.join(l.strip(' \t\r') for l in s.split('\n') if l.strip(' \t\r'))


def set_script_hash(scripts):
    """scripts: {amount: script text}. Same algorithm as rune_display_script_hash() in rune.cpp."""
    acc = b''
    for amount in sorted(scripts):
        acc += ('%u:%016x\n' % (amount, fnv1a64(normalize_script(scripts[amount]).encode('ascii')))).encode('ascii')
    return fnv1a64(acc)


# ---------------------------------------------------------------- script evaluation
LINE = re.compile(r'^(bonus2?)\s+(\w+),(?:(\w+),)?(.+);$')
TERN = re.compile(r'\(([^()?:]+)\?([^()?:]+):([^()?:]+)\)')
SAFE = re.compile(r'^[0-9\s()+\-*/<>=!?:]+$')


def eval_expr(expr, grade):
    e = expr.replace('.@grade', str(grade)).strip()
    if not SAFE.match(e):
        fail('unsupported expression %r' % expr)
    while '?' in e:
        n = TERN.sub(lambda m: str(int(eval(m.group(2) + ' if ' + m.group(1) + ' else ' + m.group(3),
                                             {'__builtins__': {}}, {}))), e)
        if n == e:
            fail('unsupported ternary %r' % expr)
        e = n
    v = eval(e, {'__builtins__': {}}, {})
    if not isinstance(v, int):
        fail('non-integer value %r from %r' % (v, expr))
    return v


def parse_script(text, where):
    lines = []
    for raw in normalize_script(text).split('\n'):
        if raw == '.@grade = getupgrade_rune();':
            continue
        m = LINE.match(raw)
        if not m:
            fail('%s: script line not understood: %r' % (where, raw))
        cmd, name, t2, expr = m.groups()
        if (cmd == 'bonus2') != (t2 is not None):
            fail('%s: %s arity mismatch: %r' % (where, cmd, raw))
        lines.append((name + (',' + t2 if t2 else ''), expr))
    return lines


def load_sets(cfg):
    doc = yaml.safe_load(open(RUNE_DB, encoding='utf-8'))
    sets = []
    for tag in doc['Body']:
        for s in tag.get('Set', []):
            sid = s['Id']
            if sid not in cfg['Sets']:
                fail('set %s (%s) has no entry in config.yml Sets' % (sid, s['Name']))
            scripts = {}
            for sc in s.get('Scripts', []):
                if sc['Amount'] in scripts:
                    fail('set %s: duplicate Amount %s' % (sid, sc['Amount']))
                if not sc['Script'].isascii():
                    fail('set %s: non-ASCII script' % sid)
                scripts[sc['Amount']] = sc['Script']
            grades = sorted(u['Grade'] for u in s.get('Upgrades', []))
            sets.append({'tag': tag['Id'], 'id': sid, 'name': s['Name'], 'scripts': scripts,
                         'tiers': {a: parse_script(t, '%s Amount %s' % (s['Name'], a)) for a, t in scripts.items()},
                         'max_grade': (grades[-1] + 1) if grades else 0, 'slots': len(s.get('Books', []))})
    missing = set(cfg['Sets']) - {s['id'] for s in sets}
    if missing:
        fail('config.yml Sets not in rune_db.yml: %s' % sorted(missing))
    return sets


def build_states(cfg, s):
    grades, pieces = cfg['Grades'], cfg['Pieces']
    if s['max_grade'] > grades - 1:
        fail('%s: grade %d does not fit Grades=%d' % (s['name'], s['max_grade'], grades))
    if s['slots'] > pieces - 1:
        fail('%s: %d slots do not fit Pieces=%d' % (s['name'], s['slots'], pieces))
    keys = []
    for amount in sorted(s['tiers']):
        for k, _ in s['tiers'][amount]:
            if k not in cfg['Bonus']:
                fail('%s: bonus %s has no wording in config.yml Bonus' % (s['name'], k))
            if k not in keys:
                keys.append(k)
    states, grid = {}, [[None] * pieces for _ in range(grades)]
    for g in range(grades):
        for p in range(pieces):
            active = tuple(a for a in sorted(s['tiers']) if p >= a)
            if not active:
                continue
            tot = dict.fromkeys(keys, 0)
            for a in active:
                for k, expr in s['tiers'][a]:
                    tot[k] += eval_expr(expr, g)
            sig = (active, tuple(tot[k] for k in keys))
            states.setdefault(sig, []).append((g, p))
            grid[g][p] = sig
    order = sorted(states, key=lambda sig: (len(sig[0]), min(gp[0] for gp in states[sig]), sig))
    base = cfg['Sets'][s['id']]['Base']
    if len(order) > cfg['StatesPerSet']:
        fail('%s has %d states > StatesPerSet %d' % (s['name'], len(order), cfg['StatesPerSet']))
    efst = {sig: base + i for i, sig in enumerate(order)}
    out = []
    for sig in order:
        active, vals = sig
        out.append({'efst': efst[sig], 'tiers': active,
                    'values': [(k, v) for k, v in zip(keys, vals) if v != 0],
                    'states': sorted(states[sig])})
    egrid = [[efst[grid[g][p]] if grid[g][p] else 0 for p in range(pieces)] for g in range(grades)]
    return out, egrid


# ---------------------------------------------------------------- text
def fmt_value(rule, v):
    a = abs(v)
    if rule.get('Unit') == 'ms_to_sec':
        txt = ('%.3f' % (a / 1000.0)).rstrip('0').rstrip('.')
    else:
        txt = str(a)
    return txt


def line_text(cfg, key, v, lang):
    rule = cfg['Bonus'][key]
    tpl = rule[lang + ('Pos' if v > 0 else 'Neg')]
    return tpl.replace('{v}', fmt_value(rule, v))


def lua_str(s):
    if '"' in s or '\\' in s or '\n' in s:
        fail('tooltip text needs escaping: %r' % s)
    return '"' + s + '"'


def tooltip_lines(cfg, setcfg, st, lang):
    title = cfg['Title'][lang].replace('{name}', setcfg[lang])
    tiers = cfg['Tiers'][lang].replace('{tiers}', cfg['Tiers']['Join'].join(str(t) for t in st['tiers']))
    return [title, tiers] + [line_text(cfg, k, v, lang) for k, v in st['values']]


# ---------------------------------------------------------------- outputs
def efst_symbol(setcfg, efst):
    return 'EFST_NEED_RUNE_%s_%02d' % (setcfg['Key'], efst - setcfg['Base'] + 1)


def block(lines):
    return ('\r\n'.join([BEGIN] + lines + [END]) + '\r\n')


def replace_tail_block(base, new_block, enc):
    """Strip a previous generated block (appended at the end) and append the new one."""
    b = base.decode(enc)
    i = b.find('\r\n' + BEGIN)
    if i >= 0:
        j = b.find(END, i)
        if j < 0:
            fail('unterminated generated block')
        b = b[:i] + b[j + len(END) + 2:]
    return (b + '\r\n' + new_block).encode(enc)


def strip_tail_block(data, enc='cp949'):
    b = data.decode(enc)
    i = b.find('\r\n' + BEGIN)
    if i < 0:
        return data
    j = b.find(END, i)
    return (b[:i] + b[j + len(END) + 2:]).encode(enc)


def gen_efstids(base, all_states):
    b = base
    if b'[NEED RUNE TOOLTIP BEGIN]' in b:
        i = b.find(b'\t' + BEGIN.encode())
        j = b.find(END.encode(), i)
        b = b[:i] + b[j + len(END) + 2:]
    if b.count(EFST_ANCHOR) != 1:
        fail('efstids.lub anchor %r not found exactly once' % EFST_ANCHOR)
    lines = ['\t' + BEGIN] + ['\t%s = %d,' % (sym, e) for sym, e in all_states] + ['\t' + END]
    ins = ('\r\n'.join(lines) + '\r\n').encode('ascii')
    for sym, e in all_states:
        if re.search(rb'= %d,' % e, b):
            fail('efstids.lub already uses id %d' % e)
    return b.replace(EFST_ANCHOR, EFST_ANCHOR + ins)


def gen_stateiconinfo(cfg, sets_states, lang):
    out = []
    for s, states in sets_states:
        sc = cfg['Sets'][s['id']]
        for st in states:
            lines = tooltip_lines(cfg, sc, st, lang)
            out.append('StateIconList[%d] = { -- %s' % (st['efst'], efst_symbol(sc, st['efst'])))
            out.append('\tdescript = {')
            out.append('\t\t{ %s, COLOR_TITLE_BUFF },' % lua_str(lines[0]))
            for t in lines[1:]:
                out.append('\t\t{ %s },' % lua_str(t))
            out.append('\t}')
            out.append('}')
    return block(out)


def gen_imginfo(cfg, sets_states):
    out = ['if StateIconImgList[PRIORITY_GOLD] == nil then', '\tStateIconImgList[PRIORITY_GOLD] = {}', 'end']
    for s, states in sets_states:
        sc = cfg['Sets'][s['id']]
        for st in states:
            out.append('StateIconImgList[PRIORITY_GOLD][%d] = "%s"' % (st['efst'], icon_name(sc)))
    return block(out)


def gen_f(sets_states):
    return block(['HaveEfstImgTable[%d] = true' % st['efst'] for _, states in sets_states for st in states])


def icon_name(sc):
    return 'need_rune_%s.tga' % sc['Key'].lower()


def make_tga(src_bmp):
    from PIL import Image
    im = Image.open(src_bmp).convert('RGB').resize((32, 32), Image.LANCZOS).convert('RGBA')
    w, h = im.size
    hdr = bytes([0, 0, 2, 0, 0, 0, 0, 0, 0, 0, 0, 0, w & 255, w >> 8, h & 255, h >> 8, 32, 8])
    px = im.load()
    body = bytearray()
    for y in range(h - 1, -1, -1):            # bottom-left origin, like need_grace.tga
        for x in range(w):
            r, g, b, a = px[x, y]
            body += bytes([b, g, r, a])
    return hdr + bytes(body) + TGA_FOOTER


def gen_server(cfg, sets_states, grids, db_sha):
    G, P = cfg['Grades'], cfg['Pieces']
    maxl = max(len(st['values']) for _, states in sets_states for st in states)
    o = ['// GENERATED by tools/need_rune_tooltip/generate.py from db/rune_db.yml - do not edit by hand.',
         '// rune_db.yml sha256 %s' % db_sha,
         '// Display only: maps the active rune set state to the EFST whose client tooltip holds the exact',
         '// summed values, and lists the bonuses that state must produce (checked by @runetooltipcheck).',
         '',
         '#define NEED_RUNE_DISPLAY_EFST_FIRST %d' % cfg['EfstFirst'],
         '#define NEED_RUNE_DISPLAY_EFST_LAST %d' % cfg['EfstLast'],
         '#define NEED_RUNE_DISPLAY_GRADES %d' % G,
         '#define NEED_RUNE_DISPLAY_PIECES %d' % P,
         '#define NEED_RUNE_DISPLAY_MAX_BONUS %d' % maxl,
         '',
         'static const s_rune_display_state rune_display_states[] = {']
    for s, states in sets_states:
        for st in states:
            bon = []
            for k, v in st['values']:
                r = cfg['Bonus'][k]
                bon.append('{ %s, %s, %d }' % (r['Sp'], r.get('Type2', NO_TYPE2), v))
            o.append('\t{ %d, %u, %d, { %s } }, // %s %s' % (
                st['efst'], s['id'], len(bon), ', '.join(bon),
                s['name'], ' / '.join('%s %d' % kv for kv in st['values'])))
    o.append('};')
    o.append('')
    o.append('static const s_rune_display_set rune_display_sets[] = {')
    for (s, _), grid in zip(sets_states, grids):
        rows = ',\n\t\t'.join('{ %s }' % ', '.join('%d' % e for e in row) for row in grid)
        o.append('\t{ %d, %u, 0x%016xULL, // %s' % (s['tag'], s['id'], set_script_hash(s['scripts']), s['name']))
        o.append('\t\t{ ' + rows + ' } },')
    o.append('};')
    return ('\n'.join(o) + '\n').replace('\n', '\r\n').encode('ascii')   # CRLF like the other src files (autocrlf checkouts)


def generate(cfg, kr, en, icon_root=None):
    """icon_root: KR repo holding the rune UI bmps (default: kr)."""
    sets = load_sets(cfg)
    sets.sort(key=lambda s: cfg['Sets'][s['id']]['Base'])
    sets_states, grids, all_syms = [], [], []
    used = set()
    for s in sets:
        states, grid = build_states(cfg, s)
        sc = cfg['Sets'][s['id']]
        for st in states:
            e = st['efst']
            if not (cfg['EfstFirst'] <= e <= cfg['EfstLast']) or e in used:
                fail('EFST %d out of the reserved block or reused' % e)
            used.add(e)
            all_syms.append((efst_symbol(sc, e), e))
        sets_states.append((s, states))
        grids.append(grid)
    db_sha = hashlib.sha256(open(RUNE_DB, 'rb').read()).hexdigest()
    files = {('rathena', SERVER_INC): gen_server(cfg, sets_states, grids, db_sha)}

    def rd(root, rel):
        return open(os.path.join(root, rel), 'rb').read()

    common = {}
    common[os.path.join(STATEICON, 'efstids.lub')] = gen_efstids(rd(kr, os.path.join(STATEICON, 'efstids.lub')), all_syms)
    common[os.path.join(STATEICON, 'stateiconimginfo.lub')] = replace_tail_block(
        rd(kr, os.path.join(STATEICON, 'stateiconimginfo.lub')), gen_imginfo(cfg, sets_states), 'cp949')
    common[os.path.join(STATEICON, 'stateiconinfo_f.lub')] = replace_tail_block(
        rd(kr, os.path.join(STATEICON, 'stateiconinfo_f.lub')), gen_f(sets_states), 'cp949')
    for s, _ in sets_states:
        sc = cfg['Sets'][s['id']]
        common[os.path.join(EFFECT, icon_name(sc))] = make_tga(os.path.join(icon_root or kr, ICON_SRC, sc['Icon'] + '.bmp'))
    for rel, data in common.items():
        files[('kr', rel)] = data
        files[('en', rel)] = data
    for lang, root, key in (('Kr', kr, 'kr'), ('En', en, 'en')):
        rel = os.path.join(STATEICON, 'stateiconinfo.lub')
        data = replace_tail_block(rd(root, rel), gen_stateiconinfo(cfg, sets_states, lang), 'cp949')
        if key == 'en' and re.search(rb'[\x80-\xff]', data[len(strip_tail_block(data)):]):
            fail('EN tooltip block is not ASCII')
        files[(key, rel)] = data
    return files, sets_states


def report(cfg, sets_states):
    o = ['# Rune tooltip states (generated)', '',
         '| EFST | set | tiers | grades x pieces | KR lines | EN lines |', '|---|---|---|---|---|---|']
    for s, states in sets_states:
        sc = cfg['Sets'][s['id']]
        for st in states:
            gp = st['states']
            g = sorted({x[0] for x in gp}); p = sorted({x[1] for x in gp})
            o.append('| %d | %s | %s | +%d~%d x %s | %s | %s |' % (
                st['efst'], s['name'], '/'.join(map(str, st['tiers'])), g[0], g[-1], ','.join(map(str, p)),
                '<br>'.join(tooltip_lines(cfg, sc, st, 'Kr')), '<br>'.join(tooltip_lines(cfg, sc, st, 'En'))))
    return '\n'.join(o) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--kr', required=True, help='KR client repo root (NEEDResoruce)')
    ap.add_argument('--en', required=True, help='EN client repo root (NEEDResoruce_EN)')
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument('--out', help='write everything under this folder (rathena/, kr/, en/)')
    g.add_argument('--install', action='store_true', help='write into rathena and both client repos')
    g.add_argument('--check', action='store_true', help='compare with the repos, exit 1 on drift')
    a = ap.parse_args()
    cfg = yaml.safe_load(open(os.path.join(HERE, 'config.yml'), encoding='utf-8'))
    files, sets_states = generate(cfg, a.kr, a.en)
    roots = {'rathena': REPO, 'kr': a.kr, 'en': a.en}
    n_states = sum(len(st) for _, st in sets_states)
    drift = []
    for (where, rel), data in sorted(files.items()):
        if a.out:
            p = os.path.join(a.out, where, rel)
        else:
            p = os.path.join(roots[where], rel)
        if a.check:
            if not os.path.isfile(p) or open(p, 'rb').read() != data:
                drift.append('%s:%s' % (where, rel))
            continue
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, 'wb') as f:
            f.write(data)
    if a.out:
        with open(os.path.join(a.out, 'states.md'), 'w', encoding='utf-8') as f:
            f.write(report(cfg, sets_states))
    print('sets %d, states %d, files %d' % (len(sets_states), n_states, len(files)))
    if a.check:
        for d in drift:
            print('DRIFT', d)
        print('CHECK', 'FAIL' if drift else 'PASS')
        return 1 if drift else 0
    return 0


if __name__ == '__main__':
    sys.exit(main())
