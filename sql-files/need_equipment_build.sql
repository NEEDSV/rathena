CREATE TABLE IF NOT EXISTS `need_equipment_build_admin_log` (
  `log_id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `build_id` bigint unsigned NOT NULL,
  `admin_account_id` int unsigned NOT NULL,
  `admin_char_id` int unsigned NOT NULL,
  `action` varchar(30) NOT NULL,
  `reason` varchar(200) NOT NULL DEFAULT '',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`log_id`),
  KEY `idx_need_build_admin_log_build` (`build_id`,`created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=euckr COLLATE=euckr_korean_ci;

CREATE TABLE IF NOT EXISTS `need_equipment_build_reward_log` (
  `reward_log_id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `build_id` bigint unsigned NOT NULL,
  `account_id` int unsigned NOT NULL,
  `char_id` int unsigned NOT NULL,
  `reward_item_id` int unsigned NOT NULL,
  `reward_amount` int unsigned NOT NULL,
  `claimed_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`reward_log_id`),
  UNIQUE KEY `uq_need_build_reward_build` (`build_id`),
  KEY `idx_need_build_reward_account` (`account_id`,`claimed_at`)
) ENGINE=InnoDB DEFAULT CHARSET=euckr COLLATE=euckr_korean_ci;
