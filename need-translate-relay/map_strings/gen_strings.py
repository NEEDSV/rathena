def c_escape_bytes(b: bytes) -> str:
    out = []
    for ch in b:
        if ch == 0x22:
            out.append('\\"')
        elif ch == 0x5C:
            out.append('\\\\')
        elif 0x20 <= ch < 0x7F:
            out.append(chr(ch))
        else:
            # always three digits: an octal escape stops after three, so a following
            # digit can never merge into it (unlike a hex escape)
            out.append('\\%03o' % ch)
    return ''.join(out)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.abspath(os.path.join(here, '..', '..'))
    dst = os.path.join(root, 'src', 'map', 'need_chat_translate_strings.inc')
    lines = [
        '// NEED Chat Translate v1 - GENERATED by need-translate-relay/map_strings/gen_strings.py. Do not edit.',
        '// [0] = Korean (CP949 bytes as octal escapes), [1] = English.',
        '#ifndef NEED_CHAT_TRANSLATE_STRINGS_INC',
        '#define NEED_CHAT_TRANSLATE_STRINGS_INC',
        '',
    ]
    for ident, kr, en in STRINGS:
        krb = kr.encode('cp949')
        enb = en.encode('ascii')
        lines.append('static const char* const NCT_S_%s[2] = { "%s", "%s" };' % (ident, c_escape_bytes(krb), c_escape_bytes(enb)))
    lines += ['', '#endif // NEED_CHAT_TRANSLATE_STRINGS_INC', '']
    data = '\n'.join(lines).encode('ascii')
    with open(dst, 'wb') as f:
        f.write(data)
    print('wrote', dst, len(STRINGS), 'strings')
    return 0


if __name__ == '__main__':
    sys.exit(main())
